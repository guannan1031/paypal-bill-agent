"""PayPal Invoicing integration - the "get paid" side of the bill agent.

Sandbox API: api-m.sandbox.paypal.com/v2/invoicing/invoices
  create -> send -> (client pays) -> get (reconcile payment status)
Without credentials the same endpoints run in MOCK mode against an in-memory
book, mirroring the real API response shapes (responses carry mode:"mock"),
so the full demo loop works with zero credentials.

This module intentionally stays import-light (httpx only), same style as
the Orders v2 flow in app.py.
"""
import uuid
from typing import Callable

import httpx
from fastapi import HTTPException
from pydantic import BaseModel, Field

INVOICES: dict[str, dict] = {}  # MOCK invoice book (demo only)

SANDBOX_INVOICES = "https://api-m.sandbox.paypal.com/v2/invoicing/invoices"


class InvoiceItem(BaseModel):
    name: str = Field(description="Item / service description")
    amount: float
    currency: str = "USD"
    quantity: int = 1


class InvoiceCreateRequest(BaseModel):
    client_name: str = Field(description="Client / payer name")
    client_email: str | None = Field(default=None, description="Sandbox send target")
    items: list[InvoiceItem]
    note: str | None = None


class InvoiceSendRequest(BaseModel):
    invoice_id: str
    client_email: str | None = None


def _total(items: list[InvoiceItem]) -> tuple[float, str]:
    currencies = {i.currency for i in items}
    if len(currencies) > 1:
        raise HTTPException(400, f"mixed currencies not supported: {sorted(currencies)}")
    return round(sum(i.amount * i.quantity for i in items), 2), items[0].currency


def _name_of(value) -> str:
    """PayPal v2 name can be a full_name object or a plain string."""
    if isinstance(value, dict):
        return value.get("full_name") or value.get("given_name") or ""
    return value or ""


def _mock_invoice(req: InvoiceCreateRequest) -> dict:
    total, currency = _total(req.items)
    inv_id = "INV-MOCK-" + uuid.uuid4().hex[:8].upper()
    inv = {
        "invoice_id": inv_id,
        "status": "DRAFT",
        "mode": "mock",
        "client_name": req.client_name,
        "client_email": req.client_email,
        "note": req.note,
        "currency": currency,
        "amount": f"{total:.2f}",
        "items": [i.model_dump() for i in req.items],
        "payments": [],
    }
    INVOICES[inv_id] = inv
    return inv


def register_invoicing_routes(app, mode: str, get_token: Callable[[], str], invoicer_name: str) -> None:
    """Attach /api/invoices/* endpoints to the FastAPI app."""
    def _via_toolkit(op: str, payload):
        """Route a sandbox call through the official Agent Toolkit bridge; None -> caller falls back to direct REST."""
        if mode != "sandbox":
            return None
        try:
            try:
                from . import toolkit_bridge as tb
            except ImportError:
                import toolkit_bridge as tb
            fn = getattr(tb, op, None)
            if fn is None:
                return None
            return fn(payload)
        except Exception:
            return None


    def _sandbox_create(req: InvoiceCreateRequest) -> dict:
        total, currency = _total(req.items)
        recipient: dict = {"billing_info": {"name": {"full_name": req.client_name}}}
        if req.client_email:
            recipient["billing_info"]["email_address"] = {"address": req.client_email}
        payload = {
            "detail": {
                "invoice_number": "BA-" + uuid.uuid4().hex[:6].upper(),
                "currency_code": currency,
                "note": req.note or "Generated by AI Bill & Invoice Agent",
                "terms_and_conditions": "Demo only - PayPal sandbox, no real money.",
            },
            "invoicer": {
                "business_name": invoicer_name,
                "email_address": {"address": "demo@billagent.example.com"},
            },
            "primary_recipients": [recipient],
            "items": [
                {
                    "name": i.name[:60],
                    "quantity": str(i.quantity),
                    "unit_amount": {"currency_code": currency, "value": f"{i.amount:.2f}"},
                    "unit_of_measure": "QUANTITY",
                }
                for i in req.items
            ],
            "amount": {
                "breakdown": {"item_total": {"currency_code": currency, "value": f"{total:.2f}"}},
                "currency_code": currency,
                "value": f"{total:.2f}",
            },
        }
        with httpx.Client(timeout=30) as client:
            resp = client.post(
                SANDBOX_INVOICES,
                headers={"Authorization": f"Bearer {get_token()}", "Content-Type": "application/json"},
                json=payload,
            )
            resp.raise_for_status()
            inv = resp.json()
        return {
            "invoice_id": inv.get("id", ""),
            "status": inv.get("status", "DRAFT"),
            "mode": mode,
            "client_name": req.client_name,
            "client_email": req.client_email,
            "currency": currency,
            "amount": f"{total:.2f}",
            "items": [i.model_dump() for i in req.items],
            "payments": [],
        }

    def _sandbox_send(invoice_id: str, email: str | None) -> dict:
        body: dict = {}
        if email:
            body["send_to"] = [{"email_address": email}]
        with httpx.Client(timeout=30) as client:
            resp = client.post(
                f"{SANDBOX_INVOICES}/{invoice_id}/send",
                headers={"Authorization": f"Bearer {get_token()}", "Content-Type": "application/json"},
                json=body,
            )
            resp.raise_for_status()
            resp.json()
        return {"invoice_id": invoice_id, "status": "SENT", "mode": mode, "sent_to": email or "recipient on file"}

    def _sandbox_get(invoice_id: str) -> dict:
        with httpx.Client(timeout=30) as client:
            resp = client.get(
                f"{SANDBOX_INVOICES}/{invoice_id}",
                headers={"Authorization": f"Bearer {get_token()}"},
            )
            resp.raise_for_status()
            inv = resp.json()
        payments = []
        for p in inv.get("payments") or []:
            tx = p.get("transaction_info") or {}
            payments.append(
                {
                    "transaction_id": tx.get("transaction_id") or tx.get("transaction_code"),
                    "amount": (tx.get("transaction_amount") or {}).get("value"),
                    "currency": (tx.get("transaction_amount") or {}).get("currency_code"),
                    "date": tx.get("date"),
                    "status": "PAID",
                }
            )
        recipient = (inv.get("primary_recipients") or [{}])[0].get("billing_info") or {}
        return {
            "invoice_id": inv.get("id", invoice_id),
            "status": inv.get("status", "UNKNOWN"),
            "mode": mode,
            "client_name": _name_of(recipient.get("name")),
            "currency": (inv.get("amount") or {}).get("currency_code"),
            "amount": (inv.get("amount") or {}).get("value"),
            "items": [
                {
                    "name": it.get("name", ""),
                    "amount": float((it.get("unit_amount") or {}).get("value", 0) or 0),
                    "currency": (it.get("unit_amount") or {}).get("currency_code", "USD"),
                    "quantity": int(float(it.get("quantity", 1) or 1)),
                }
                for it in inv.get("items") or []
            ],
            "payments": payments,
        }

    @app.post("/api/invoices/create")
    def create_invoice(req: InvoiceCreateRequest):
        if not req.items:
            raise HTTPException(400, "invoice needs at least one item")
        try:
            inv = None
            if mode == "sandbox":
                inv = _via_toolkit("invoice_create", req.model_dump())
                if inv is None:
                    inv = _sandbox_create(req)
            else:
                inv = _mock_invoice(req)
        except httpx.HTTPError as e:
            return {"error": f"PayPal Invoicing API failed: {e}", "mode": mode}
        return inv

    @app.post("/api/invoices/send")
    def send_invoice(payload: InvoiceSendRequest):
        inv_id = payload.invoice_id
        if not inv_id:
            raise HTTPException(400, "missing invoice_id")
        if mode == "sandbox":
            try:
                sent = _via_toolkit("invoice_send", {"invoice_id": inv_id, "client_email": payload.client_email})
                if sent is None:
                    sent = _sandbox_send(inv_id, payload.client_email)
                return sent
            except httpx.HTTPError as e:
                return {"error": f"PayPal Invoicing API failed: {e}", "mode": mode}
        inv = INVOICES.get(inv_id)
        if not inv:
            raise HTTPException(404, "invoice not found (mock book is in-memory; recreate it)")
        inv["status"] = "SENT"
        inv["client_email"] = payload.client_email or inv.get("client_email")
        return {"invoice_id": inv_id, "status": "SENT", "mode": mode, "sent_to": inv.get("client_email") or "recipient on file"}

    @app.get("/api/invoices/{invoice_id}")
    def get_invoice(invoice_id: str):
        if mode == "sandbox":
            try:
                got = _via_toolkit("invoice_get", {"invoice_id": invoice_id})
                if got is None:
                    got = _sandbox_get(invoice_id)
                return got
            except httpx.HTTPError as e:
                return {"error": f"PayPal Invoicing API failed: {e}", "mode": mode}
        inv = INVOICES.get(invoice_id)
        if not inv:
            raise HTTPException(404, "invoice not found")
        return inv

    @app.post("/api/invoices/{invoice_id}/simulate-payment")
    def simulate_payment(invoice_id: str):
        """MOCK/demo reconciliation aid: mark a sent invoice as paid so judges can
        see the reconcile step. Sandbox mode returns 400 (real payments come from PayPal)."""
        if mode == "sandbox":
            raise HTTPException(400, "sandbox invoices are paid via PayPal; simulate is mock-only")
        inv = INVOICES.get(invoice_id)
        if not inv:
            raise HTTPException(404, "invoice not found")
        if inv["status"] == "DRAFT":
            raise HTTPException(400, "send the invoice before payment")
        inv["status"] = "PAID"
        inv["payments"] = [
            {
                "transaction_id": "MOCKPAY-" + uuid.uuid4().hex[:8].upper(),
                "amount": inv["amount"],
                "currency": inv["currency"],
                "date": "demo",
                "status": "PAID",
            }
        ]
        return inv

    @app.get("/api/invoices")
    def list_invoices():
        if mode == "sandbox":
            via = _via_toolkit("invoice_list", {})
            if via is not None:
                return via
            try:
                with httpx.Client(timeout=30) as client:
                    resp = client.get(
                        f"{SANDBOX_INVOICES}?total_required=true&page_size=10",
                        headers={"Authorization": f"Bearer {get_token()}"},
                    )
                    resp.raise_for_status()
                    data = resp.json()
                return {"mode": mode, "invoices": [
                    {
                        "invoice_id": it.get("id", ""),
                        "status": it.get("status", ""),
                        "amount": (it.get("amount") or {}).get("value"),
                        "currency": (it.get("amount") or {}).get("currency_code"),
                    }
                    for it in data.get("invoices") or []
                ]}
            except httpx.HTTPError as e:
                return {"error": f"PayPal Invoicing API failed: {e}", "mode": mode}
        return {"mode": mode, "invoices": [
            {k: inv.get(k) for k in ("invoice_id", "status", "amount", "currency")} for inv in INVOICES.values()
        ]}
